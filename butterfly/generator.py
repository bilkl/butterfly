"""Le générateur : traduit l'arbre vérifié en texte Python.

Le point clé est la **propagation**. Butterfly n'embarque aucun moteur réactif à
l'exécution : le compilateur calcule, pour chaque affectation d'une cellule
source, la liste ordonnée des cellules dérivées à recalculer et des
observateurs à prévenir, puis écrit le code qui le fait.

Pour ``quantite = 5;`` dans le programme

    soit prix = 20;  soit quantite = 3;
    lie total = prix * quantite;
    quand total { affiche total; }

le code généré est :

    _old_total = v_total          # on retient la valeur avant
    v_quantite = 5
    v_total = _calc_total()      # on recalcule ce qui dépend de quantite
    if _change(_old_total, v_total):
        _obs_0()                 # on prévient l'observateur si la valeur a changé

Les cellules dérivées sont recalculées dans l'ordre de leur déclaration, qui est
un ordre topologique valide puisqu'on déclare avant d'utiliser : chaque cellule
est recalculée une seule fois, après toutes celles dont elle dépend.
"""

from butterfly.nodes import (
    Assignment,
    Binary,
    Binding,
    Block,
    Boolean,
    Call,
    Declaration,
    Expression,
    For,
    If,
    Integer,
    Name,
    Observer,
    Print,
    Statement,
    Text,
    Unary,
)
from butterfly.semantics import Analysis, SymbolKind

#: Fonction du runtime associée à chaque opérateur binaire « simple ».
OPERATORS = {
    "+": "_add",
    "-": "_sub",
    "*": "_mul",
    "/": "_div",
    "%": "_mod",
    "<": "_lt",
    "<=": "_le",
    ">": "_gt",
    ">=": "_ge",
}

INDENTATION = "    "


def python_name(name: str) -> str:
    """Le nom Python d'une variable Butterfly : toujours préfixé par ``v_``."""
    return f"v_{name}"


class PythonGenerator:
    """Génère le texte Python d'un programme analysé."""

    def __init__(self, analysis: Analysis) -> None:
        self.analysis = analysis
        self.lines: list[str] = []
        self.used: set[str] = set()
        # Ce qu'on a rencontré *jusqu'ici* dans le programme, dans l'ordre :
        # une affectation ne concerne que ce qui est déjà déclaré à cet endroit.
        self.bound_cells: list[str] = []
        self.observers: list[tuple[int, str]] = []

    # --- Sortie -------------------------------------------------------------

    def generate(self) -> str:
        for statement in self.analysis.program.statements:
            self.statement(statement, 0)
        header = ["# Generated by Butterfly (butterfly transpile): do not modify."]
        if self.used:
            names = ", ".join(sorted(self.used))
            header.append(f"from butterfly.runtime import {names}")
        return "\n".join([*header, "", *self.lines]) + "\n"

    def write_line(self, indentation: int, text: str) -> None:
        self.lines.append(INDENTATION * indentation + text)

    def use(self, function: str) -> str:
        self.used.add(function)
        return function

    # --- Instructions -------------------------------------------------------

    def block(self, block: Block, indentation: int) -> None:
        if not block.statements:
            self.write_line(indentation, "pass")
        for statement in block.statements:
            self.statement(statement, indentation)

    def statement(
        self, statement: Statement | Binding | Observer, indentation: int
    ) -> None:
        match statement:
            case Declaration(name=name, value=value):
                self.write_line(
                    indentation, f"{python_name(name)} = {self.expr(value)}"
                )
            case Binding(name=name, value=value):
                self.binding(name, value)
            case Assignment(name=name, value=value):
                self.assignment(name, value, indentation)
            case If() as if_stmt:
                self.if_stmt(if_stmt, indentation)
            case For() as for_stmt:
                self.for_stmt(for_stmt, indentation)
            case Print(values=values):
                arguments = ", ".join(self.expr(value) for value in values)
                self.write_line(indentation, f"{self.use('_print')}({arguments})")
            case Observer() as observer:
                self.observer(observer)

    def binding(self, name: str, value: Expression) -> None:
        # Une fonction par cellule dérivée : on la rappelle à chaque recalcul.
        self.write_line(0, f"def _calc_{name}():")
        self.write_line(1, f"return {self.expr(value)}")
        self.write_line(0, f"{python_name(name)} = _calc_{name}()")
        self.bound_cells.append(name)

    def observer(self, observer: Observer) -> None:
        number = len(self.observers)
        self.write_line(0, f"def _obs_{number}():")
        self.block(observer.body, 1)
        self.observers.append((number, observer.target))

    def assignment(self, name: str, value: Expression, indentation: int) -> None:
        kind = self.analysis.kinds.get(name)
        if kind is not SymbolKind.SOURCE:  # une variable locale : rien à propager
            self.write_line(indentation, f"{python_name(name)} = {self.expr(value)}")
            return
        # 1. Quelles cellules dérivées dépendent (même de loin) de `nom` ?
        touched = {name}
        to_recompute: list[str] = []
        for cell in self.bound_cells:
            if self.analysis.dependencies[cell] & touched:
                touched.add(cell)
                to_recompute.append(cell)
        # 2. Lesquelles sont observées ?
        observed = {target for _, target in self.observers}
        watched = [c for c in [name, *to_recompute] if c in observed]
        # 3. On retient les valeurs d'avant, on affecte, on recalcule, on notifie.
        for cell in watched:
            self.write_line(indentation, f"_old_{cell} = {python_name(cell)}")
        self.write_line(indentation, f"{python_name(name)} = {self.expr(value)}")
        for cell in to_recompute:
            self.write_line(indentation, f"{python_name(cell)} = _calc_{cell}()")
        for number, target in self.observers:
            if target in watched:
                change = self.use("_changed")
                self.write_line(
                    indentation,
                    f"if {change}(_old_{target}, {python_name(target)}):",
                )
                self.write_line(indentation + 1, f"_obs_{number}()")

    def if_stmt(self, if_stmt: If, indentation: int) -> None:
        condition = self.use("_condition")
        self.write_line(
            indentation,
            f"if {condition}({self.expr(if_stmt.condition)}, {if_stmt.position.line}):",
        )
        self.block(if_stmt.then_block, indentation + 1)
        rest = if_stmt.else_branch
        while isinstance(rest, If):
            self.write_line(
                indentation,
                f"elif {condition}({self.expr(rest.condition)}, {rest.position.line}):",
            )
            self.block(rest.then_block, indentation + 1)
            rest = rest.else_branch
        if isinstance(rest, Block):
            self.write_line(indentation, "else:")
            self.block(rest, indentation + 1)

    def for_stmt(self, for_stmt: For, indentation: int) -> None:
        bound = self.use("_bound")
        line = for_stmt.position.line
        start = f"{bound}({self.expr(for_stmt.start)}, {line})"
        end = f"{bound}({self.expr(for_stmt.end)}, {line})"
        self.write_line(
            indentation,
            f"for {python_name(for_stmt.variable)} in range({start}, {end}):",
        )
        self.block(for_stmt.body, indentation + 1)

    # --- Expressions --------------------------------------------------------

    def expr(self, expression: Expression) -> str:
        match expression:
            case Integer(value=value):
                return str(value)
            case Text(value=value):
                return repr(value)
            case Boolean(value=value):
                return "True" if value else "False"
            case Name(name=name):
                return python_name(name)
            case Unary(operator="-", operand=operand, position=position):
                return f"{self.use('_neg')}({self.expr(operand)}, {position.line})"
            case Unary(operand=operand, position=position):  # non
                boolean = self.use("_boolean")
                return f"(not {boolean}({self.expr(operand)}, {position.line}))"
            case Binary() as binary:
                return self.binary(binary)
            case Call(name=name, arguments=arguments, position=position):
                function = self.use(f"_{name}")
                values = ", ".join(self.expr(argument) for argument in arguments)
                return f"{function}({values}, {position.line})"
        raise AssertionError(f"expression inconnue : {expression!r}")

    def binary(self, expression: Binary) -> str:
        operator = expression.operator
        left = self.expr(expression.left)
        right = self.expr(expression.right)
        line = expression.position.line
        if operator == "==":
            return f"{self.use('_eq')}({left}, {right})"
        if operator == "!=":
            return f"(not {self.use('_eq')}({left}, {right}))"
        if operator in ("and", "or"):
            boolean = self.use("_boolean")
            word = "and" if operator == "and" else "or"
            return f"({boolean}({left}, {line}) {word} {boolean}({right}, {line}))"
        function = self.use(OPERATORS[operator])
        return f"{function}({left}, {right}, {line})"


def generate_python(analysis: Analysis) -> str:
    """Le texte Python correspondant à un programme analysé."""
    return PythonGenerator(analysis).generate()
